package se.imorn.feature.today

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import dev.zacsweers.metro.AppScope
import dev.zacsweers.metro.ContributesIntoMap
import dev.zacsweers.metro.Inject
import dev.zacsweers.metrox.viewmodel.ViewModelKey
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch
import se.imorn.coach.AssistantAvailability
import se.imorn.coach.AssistantPrompt
import se.imorn.coach.AssistantRequest
import se.imorn.coach.LanguageModel

/** What the Today screen shows. Nothing here is persisted yet; the scaffold's job is to prove the AI wiring. */
data class TodayUiState(
    val availability: AssistantAvailability = AssistantAvailability.Unknown,
    val writing: Boolean = false,
    val message: String? = null,
    val failed: Boolean = false,
)

/**
 * Today's ViewModel. Its one job is to drive the on-device assistant (Gemini Nano): ask whether the model is there,
 * let the user download it, and have it explain the project's next step in the user's words. The plan itself is
 * never generated by the model.
 */
@ViewModelKey
@ContributesIntoMap(AppScope::class)
@Inject
class TodayViewModel(
    /** Gemini Nano on the device. Bound in :core:data and chosen nowhere else. */
    private val languageModel: LanguageModel,
) : ViewModel() {
    private val _state = MutableStateFlow(TodayUiState())
    val state: StateFlow<TodayUiState> = _state.asStateFlow()

    /** Asks the system whether Gemini Nano can run here. Called when the screen is shown, never in the background. */
    fun checkAssistant() {
        viewModelScope.launch {
            val availability = languageModel.availability()
            _state.update { it.copy(availability = availability) }
        }
    }

    /** The user asked for Gemini Nano: AICore downloads it and keeps it up to date. */
    fun downloadAssistant() {
        _state.update { it.copy(availability = AssistantAvailability.Downloading, failed = false) }
        viewModelScope.launch {
            val done = languageModel.download()
            val availability = if (done) AssistantAvailability.Available else languageModel.availability()
            _state.update { it.copy(availability = availability, failed = !done) }
        }
    }

    /** Lets Gemini Nano explain the current project, from [request] in the user's language. */
    fun askAssistant(request: AssistantRequest) {
        _state.update { it.copy(writing = true, message = null, failed = false) }
        viewModelScope.launch {
            val answer = languageModel.write(AssistantPrompt.build(request))
                .map(AssistantPrompt::clean)
                .getOrNull()
                ?.takeIf { it.isNotBlank() }
            _state.update { it.copy(writing = false, message = answer, failed = answer == null) }
        }
    }
}
